// GenerateStandaloneHTML generates a self-contained HTML page listing all verified MEGA accounts with copy buttons
func GenerateStandaloneHTML(accounts []*storage.Account) string {
	var rows strings.Builder
	for idx, acc := range accounts {
		if acc.Status != "verified" {
			continue
		}
		rows.WriteString(fmt.Sprintf(`
      <tr>
        <td>%d</td>
        <td><code>%s</code></td>
        <td><code>%s</code></td>
        <td><code>mega_%d:</code></td>
        <td>
          <button onclick="navigator.clipboard.writeText('%s:%s'); alert('Copied %s');">Copy Credentials</button>
        </td>
      </tr>`, idx+1, acc.Email, acc.MegaPassword, idx+1, acc.Email, acc.MegaPassword, acc.Email))
	}

	return fmt.Sprintf(`<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <title>MEGA Accounts Directory</title>
  <style>
    body { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif; background: #0f172a; color: #f8fafc; padding: 2rem; max-width: 900px; margin: 0 auto; }
    h1 { color: #38bdf8; font-size: 1.5rem; margin-bottom: 0.5rem; }
    p { color: #94a3b8; font-size: 0.9rem; margin-bottom: 1.5rem; }
    table { width: 100%%; border-collapse: collapse; background: #1e293b; border-radius: 8px; overflow: hidden; box-shadow: 0 4px 6px -1px rgba(0,0,0,0.1); }
    th, td { padding: 0.75rem 1rem; text-align: left; border-bottom: 1px solid #334155; font-size: 0.85rem; }
    th { background: #334155; color: #cbd5e1; font-weight: 600; }
    tr:last-child td { border-bottom: none; }
    code { font-family: monospace; background: #0f172a; padding: 0.2rem 0.4rem; border-radius: 4px; color: #38bdf8; }
    button { background: #0284c7; color: white; border: none; padding: 0.4rem 0.8rem; border-radius: 4px; cursor: pointer; font-weight: 600; font-size: 0.75rem; }
    button:hover { background: #0369a1; }
  </style>
</head>
<body>
  <h1>MEGA Accounts Index</h1>
  <p>Self-contained directory of verified MEGA accounts generated by MEGA Account Manager.</p>
  <table>
    <thead>
      <tr>
        <th>#</th>
        <th>Email</th>
        <th>MEGA Password</th>
        <th>Remote Name</th>
        <th>Actions</th>
      </tr>
    </thead>
    <tbody>
      %s
    </tbody>
  </table>
</body>
</html>`, rows.String())
}

// GenerateCloudflareWorker generates a standalone Cloudflare Worker JavaScript script hosting the account directory
func GenerateCloudflareWorker(accounts []*storage.Account) string {
	type SafeAcc struct {
		Email    string `json:"email"`
		Password string `json:"password"`
	}
	var list []SafeAcc
	for _, acc := range accounts {
		if acc.Status == "verified" {
			list = append(list, SafeAcc{Email: acc.Email, Password: acc.MegaPassword})
		}
	}
	jsonData, _ := json.MarshalIndent(list, "", "  ")

	scriptTpl := `/**
 * Cloudflare Worker for MEGA Accounts Directory
 * Deploy this script on Cloudflare Workers to host your account index securely.
 */

const ACCOUNTS = %s;

async function handleRequest(request) {
  const html = '<!DOCTYPE html>' +
  '<html lang="en">' +
  '<head>' +
  '<meta charset="UTF-8">' +
  '<title>MEGA Cloudflare Directory</title>' +
  '<style>' +
  'body { font-family: system-ui, sans-serif; background: #0f172a; color: #f8fafc; padding: 2rem; max-width: 900px; margin: 0 auto; }' +
  'h1 { color: #38bdf8; font-size: 1.5rem; }' +
  'table { width: 100%%; border-collapse: collapse; background: #1e293b; border-radius: 8px; overflow: hidden; margin-top: 1rem; }' +
  'th, td { padding: 0.75rem 1rem; text-align: left; border-bottom: 1px solid #334155; font-size: 0.85rem; }' +
  'th { background: #334155; color: #cbd5e1; }' +
  'code { font-family: monospace; background: #0f172a; padding: 0.2rem 0.4rem; border-radius: 4px; color: #38bdf8; }' +
  'button { background: #0284c7; color: white; border: none; padding: 0.4rem 0.8rem; border-radius: 4px; cursor: pointer; font-weight: 600; }' +
  '</style>' +
  '</head>' +
  '<body>' +
  '<h1>MEGA Worker Index</h1>' +
  '<p>Total Verified Accounts: ' + ACCOUNTS.length + '</p>' +
  '<table>' +
  '<thead><tr><th>#</th><th>Email</th><th>Password</th><th>Action</th></tr></thead>' +
  '<tbody>' +
  ACCOUNTS.map((acc, i) => '<tr><td>' + (i+1) + '</td><td><code>' + acc.email + '</code></td><td><code>' + acc.password + '</code></td><td><button onclick="navigator.clipboard.writeText(\'' + acc.email + ':' + acc.password + '\');alert(\'Copied\');">Copy</button></td></tr>').join('') +
  '</tbody>' +
  '</table>' +
  '</body>' +
  '</html>';

  return new Response(html, {
    headers: { 'Content-Type': 'text/html;charset=UTF-8' },
  });
}

addEventListener('fetch', event => {
  event.respondWith(handleRequest(event.request));
});
`
	return fmt.Sprintf(scriptTpl, string(jsonData))
}
