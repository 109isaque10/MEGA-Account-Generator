package rclone

import (
	"crypto/aes"
	"crypto/cipher"
	"crypto/rand"
	"encoding/base64"
	"encoding/hex"
	"fmt"
	"strings"

	"github.com/109isaque10/mega-account-generator/pkg/storage"
)

// Standard static key used by rclone for password obscuring
const rcloneKeyHex = "9c935b48730a554d6bfd7c63c886a92bd390198eb8128afbf4de162b8b95f638"

// Obscure encrypts a plaintext password using rclone's standard AES-CTR obscure cipher
func Obscure(plaintext string) (string, error) {
	key, err := hex.DecodeString(rcloneKeyHex)
	if err != nil {
		return "", err
	}

	block, err := aes.NewCipher(key)
	if err != nil {
		return "", err
	}

	iv := make([]byte, aes.BlockSize)
	if _, err := rand.Read(iv); err != nil {
		return "", err
	}

	stream := cipher.NewCTR(block, iv)
	ciphertext := make([]byte, len(plaintext))
	stream.XORKeyStream(ciphertext, []byte(plaintext))

	buf := append(iv, ciphertext...)
	return base64.RawURLEncoding.EncodeToString(buf), nil
}

// GenerateConfig generates a complete rclone.conf with individual MEGA remotes and a union remote
func GenerateConfig(accounts []*storage.Account, unionName, createPolicy string) string {
	if unionName == "" {
		unionName = "mega_union"
	}
	if createPolicy == "" {
		createPolicy = "lus" // Least Used Space - optimal for multi-account pools
	}

	var sb strings.Builder
	sb.WriteString("# Generated by MEGA Account Manager\n")
	sb.WriteString("# Rclone configuration with union backend\n\n")

	var upstreams []string
	remoteIdx := 1

	for _, acc := range accounts {
		if acc.Status != "verified" {
			continue
		}

		remoteName := fmt.Sprintf("mega_%d", remoteIdx)
		upstreams = append(upstreams, remoteName+":")

		obscuredPass, err := Obscure(acc.MegaPassword)
		if err != nil {
			obscuredPass = acc.MegaPassword
		}

		sb.WriteString(fmt.Sprintf("[%s]\n", remoteName))
		sb.WriteString("type = mega\n")
		sb.WriteString(fmt.Sprintf("user = %s\n", acc.Email))
		sb.WriteString(fmt.Sprintf("pass = %s\n\n", obscuredPass))

		remoteIdx++
	}

	// Append Union remote
	if len(upstreams) > 0 {
		sb.WriteString(fmt.Sprintf("[%s]\n", unionName))
		sb.WriteString("type = union\n")
		sb.WriteString(fmt.Sprintf("upstreams = %s\n", strings.Join(upstreams, " ")))
		sb.WriteString("action_policy = epall\n")
		sb.WriteString(fmt.Sprintf("create_policy = %s\n", createPolicy))
		sb.WriteString("search_policy = ff\n")
	}

	return sb.String()
}
